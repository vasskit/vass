#!/usr/bin/env python3
"""Generates src/grapheme_data.zig (extended grapheme cluster properties) and
src/testdata/GraphemeBreakTest.txt for src/grapheme.zig.

Re-run (Python 3, no dependencies) after downloading the Unicode data files into
a scratch directory of your choice:

    B=https://www.unicode.org/Public/UCD/latest/ucd
    mkdir /tmp/ucd && cd /tmp/ucd
    curl -fO $B/auxiliary/GraphemeBreakProperty.txt
    curl -fO $B/emoji/emoji-data.txt
    curl -fO $B/DerivedCoreProperties.txt
    curl -fO $B/auxiliary/GraphemeBreakTest.txt
    cd /path/to/vass
    python3 -I tools/gen_grapheme.py /tmp/ucd

Then run `zig build test`. The Unicode version is read from the file header and
written into the generated file.
"""
import re
import sys
import os

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = {"Consonant": 1, "Linker": 2, "Extend": 3}
EXTPICT_BIT = 0x10


def lines(path):
    with open(path, encoding="utf-8") as f:
        for raw in f:
            s = raw.split("#", 1)[0].strip()
            if s:
                yield s


def rng(field):
    if ".." in field:
        a, b = field.split("..")
    else:
        a = b = field
    return int(a, 16), int(b, 16)


def main():
    d = sys.argv[1]
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")
    with open(os.path.join(d, "GraphemeBreakProperty.txt"), encoding="utf-8") as f:
        m = re.search(r"GraphemeBreakProperty-(\d+\.\d+\.\d+)\.txt", f.readline())
    version = m.group(1)
    val = [0] * 0x110000
    for s in lines(os.path.join(d, "GraphemeBreakProperty.txt")):
        r, p = [x.strip() for x in s.split(";")]
        a, b = rng(r)
        for c in range(a, b + 1):
            val[c] |= GCB.index(p)
    for s in lines(os.path.join(d, "emoji-data.txt")):
        r, p = [x.strip() for x in s.split(";")]
        if p == "Extended_Pictographic":
            a, b = rng(r)
            for c in range(a, b + 1):
                val[c] |= EXTPICT_BIT
    for s in lines(os.path.join(d, "DerivedCoreProperties.txt")):
        parts = [x.strip() for x in s.split(";")]
        if len(parts) == 3 and parts[1] == "InCB":
            a, b = rng(parts[0])
            for c in range(a, b + 1):
                val[c] |= INCB[parts[2]] << 5
    starts, vals = [], []
    prev = 0
    starts.append(0)
    vals.append(0)
    for c in range(0x110000):
        if val[c] != prev:
            starts.append(c)
            vals.append(val[c])
            prev = val[c]
    with open(os.path.join(out_dir, "grapheme_data.zig"), "w", encoding="utf-8") as o:
        o.write("//! GENERATED by tools/gen_grapheme.py; do not edit.\n")
        o.write("//! Grapheme_Cluster_Break, Extended_Pictographic and InCB (UAX #29) as a transition table:\n")
        o.write("//! entry i says that code points from `starts[i]` up to `starts[i + 1]` have `vals[i]`.\n")
        o.write("//! vals: bits 0-3 Grapheme_Cluster_Break (see `grapheme.Prop`), bit 4 Extended_Pictographic,\n")
        o.write("//! bits 5-6 InCB (0 none, 1 Consonant, 2 Linker, 3 Extend).\n")
        o.write('pub const unicode_version = "%s";\n\n' % version)
        o.write("pub const starts = [_]u21{\n")
        for i in range(0, len(starts), 12):
            o.write("    " + ",".join("0x%X" % x for x in starts[i:i + 12]) + ",\n")
        o.write("};\n\npub const vals = [_]u8{\n")
        for i in range(0, len(vals), 24):
            o.write("    " + ",".join("0x%X" % x for x in vals[i:i + 24]) + ",\n")
        o.write("};\n")
    # Test data without the explanatory comments.
    with open(os.path.join(d, "GraphemeBreakTest.txt"), encoding="utf-8") as f:
        tests = [l.split("#", 1)[0].strip() for l in f if l.strip() and not l.startswith("#")]
    os.makedirs(os.path.join(out_dir, "testdata"), exist_ok=True)
    with open(os.path.join(out_dir, "testdata", "GraphemeBreakTest.txt"), "w", encoding="utf-8") as o:
        o.write("# GraphemeBreakTest.txt, Unicode %s, comments stripped by tools/gen_grapheme.py\n" % version)
        o.write("\n".join(t for t in tests if t) + "\n")
    print("version", version, "transitions", len(starts))


main()
