#!/usr/bin/env python3
"""Generates src/text/emoji_data.zig (the Emoji_Presentation ranges of emoji-data.txt) for src/text/emoji.zig.

    mkdir /tmp/ucd && cd /tmp/ucd
    curl -fO https://www.unicode.org/Public/UCD/latest/ucd/emoji/emoji-data.txt
    cd /path/to/vass
    python3 -I tools/gen_emoji.py /tmp/ucd

Then run `zig build test`. The Unicode version is read from the file header.
"""
import os
import re
import sys


def main():
    d = sys.argv[1]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "text", "emoji_data.zig")
    ranges = []
    version = None
    with open(os.path.join(d, "emoji-data.txt"), encoding="utf-8") as f:
        for raw in f:
            m = re.match(r"# Version: (\d+\.\d+\.\d+)", raw)
            if m:
                version = m.group(1)
            s = raw.split("#", 1)[0].strip()
            if not s:
                continue
            field, prop = [x.strip() for x in s.split(";")]
            if prop != "Emoji_Presentation":
                continue
            a, _, b = field.partition("..")
            ranges.append((int(a, 16), int(b or a, 16)))
    ranges.sort()
    merged = []
    for a, b in ranges:
        if merged and a <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], b))
        else:
            merged.append((a, b))
    with open(out, "w", encoding="utf-8") as o:
        o.write("//! GENERATED by tools/gen_emoji.py; do not edit.\n")
        o.write("//! Emoji_Presentation (UTS #51): code points drawn as colour emoji without a U+FE0F.\n")
        o.write("//! Inclusive ranges, sorted.\n")
        o.write('pub const unicode_version = "%s";\n\n' % version)
        o.write("pub const emoji_presentation = [_][2]u21{\n")
        for i in range(0, len(merged), 4):
            o.write("    " + " ".join(".{ 0x%X, 0x%X }," % r for r in merged[i:i + 4]) + "\n")
        o.write("};\n")
    print("version", version, "ranges", len(merged))


main()
